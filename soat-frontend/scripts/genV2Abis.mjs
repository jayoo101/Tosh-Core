#!/usr/bin/env node
// Regenerates src/lib/v2/abis.ts and src/lib/v2/abisV3.ts from the Foundry
// build in ../out.
//
//   (cd .. && forge build) && node scripts/genV2Abis.mjs
//
// `--check` exits 1 when a committed file differs from what the build
// produces, so CI catches an ABI that drifted from the contracts.
//
// abisV3.ts holds only what v3 adds. Every function the UI shares between the
// stacks encodes identically on both (the v3 structs differ in internalType
// alone), so v3 contracts are read through the v2 ABIs.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, '../../out')
const header = '// GENERATED by scripts/genV2Abis.mjs from the Foundry build. Do not edit.\n\n'
const abiOf = (name) => JSON.parse(readFileSync(resolve(out, `${name}.sol/${name}.json`), 'utf8')).abi

const V2_CONTRACTS = [
  ['ToshBidBook', 'V2_BIDBOOK_ABI'],
  ['ToshHookLens', 'V2_LENS_ABI'],
  ['ToshLaunchpadHook', 'V2_HOOK_ABI'],
  ['ToshFactory', 'V2_FACTORY_ABI'],
  ['ToshToken', 'V2_TOKEN_ABI'],
  ['ToshLadderTreasury', 'V2_TREASURY_ABI'],
  ['ToshLaunchGateway', 'V2_GATEWAY_ABI'],
]

const V3_EXTRAS = [
  ['ToshHookLensV3', 'V3_LENS_EXTRA_ABI', ['quoteMint']],
  ['ToshFactoryV3', 'V3_FACTORY_EXTRA_ABI', ['shelfRemaining', 'shelfCapPerAgent']],
]
const V3_ERRORS = ['ToshHookLensV3', 'ToshFactoryV3']

let v2 = header
for (const [name, exportName] of V2_CONTRACTS) {
  v2 += `export const ${exportName} = ${JSON.stringify(abiOf(name), null, 2)} as const\n\n`
}

let v3 = header
for (const [name, exportName, fns] of V3_EXTRAS) {
  const items = abiOf(name).filter((it) => it.type === 'function' && fns.includes(it.name))
  v3 += `export const ${exportName} = ${JSON.stringify(items, null, 2)} as const\n\n`
}
const seen = new Set()
const errors = []
for (const name of V3_ERRORS) {
  for (const it of abiOf(name)) {
    if (it.type !== 'error' || seen.has(it.name)) continue
    seen.add(it.name)
    errors.push(it)
  }
}
errors.sort((a, b) => a.name.localeCompare(b.name))
v3 += `/** Revert reasons a v3 shelf mint can surface from the lens or the factory. */\n`
v3 += `export const V3_ERRORS_ABI = ${JSON.stringify(errors, null, 2)} as const\n`

// v3.1 replaces the shelf ladder with one curve, so its L2 surface is read
// through these alone. The genesis and launch calls encode as in v2, except
// the lens's `genesisState`, which drops `acceptsNative`.
const V31_PARTS = [
  ['ToshLaunchpadHookV31', 'V31_HOOK_ABI', ['mintL2', 'settleL2Burn', 'l2Price', 'l2Remaining', 'l2Quota', 'l2State', 'l2Supply', 'p0', 'mintVesting']],
  ['ToshHookLensV31', 'V31_LENS_ABI', ['genesisState', 'quoteL2', 'l2State', 'l2Account']],
  ['ToshMintVesting', 'V31_VESTING_ABI', ['claim', 'lockOf', 'DURATION']],
  ['ToshFactoryV31', 'V31_FACTORY_ABI', ['registeredHooks', 'shelfCapPerAgent']],
]
let v31 = header
for (const [name, exportName, fns] of V31_PARTS) {
  const items = abiOf(name).filter((it) => it.type === 'function' && fns.includes(it.name))
  v31 += `export const ${exportName} = ${JSON.stringify(items, null, 2)} as const\n\n`
}
const seen31 = new Set()
const errors31 = []
for (const name of ['ToshLaunchpadHookV31', 'ToshFactoryV31', 'ToshMintVesting']) {
  for (const it of abiOf(name)) {
    if (it.type !== 'error' || seen31.has(it.name)) continue
    seen31.add(it.name)
    errors31.push(it)
  }
}
errors31.sort((a, b) => a.name.localeCompare(b.name))
v31 += `/** Revert reasons a v3.1 L2 mint or vesting claim can surface. */\n`
v31 += `export const V31_ERRORS_ABI = ${JSON.stringify(errors31, null, 2)} as const\n`

const targets = [
  [resolve(here, '../src/lib/v2/abis.ts'), v2],
  [resolve(here, '../src/lib/v2/abisV3.ts'), v3],
  [resolve(here, '../src/lib/v2/abisV31.ts'), v31],
]

if (process.argv.includes('--check')) {
  let stale = false
  for (const [target, body] of targets) {
    let current = ''
    try { current = readFileSync(target, 'utf8') } catch { /* missing counts as stale */ }
    if (current !== body) {
      console.error(`${target} is stale: run \`node scripts/genV2Abis.mjs\``)
      stale = true
    }
  }
  if (stale) process.exit(1)
  console.log('v2 and v3 ABIs match the build')
} else {
  for (const [target, body] of targets) {
    writeFileSync(target, body)
    console.log(`wrote ${target}`)
  }
}
