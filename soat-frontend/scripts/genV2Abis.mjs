#!/usr/bin/env node
// Regenerates src/lib/v2/abis.ts from the Foundry build in ../out.
//
//   (cd .. && forge build) && node scripts/genV2Abis.mjs
//
// `--check` exits 1 when the committed file differs from what the build
// produces, so CI catches an ABI that drifted from the contracts.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, '../../out')
const target = resolve(here, '../src/lib/v2/abis.ts')

const CONTRACTS = [
  ['ToshBidBook', 'V2_BIDBOOK_ABI'],
  ['ToshHookLens', 'V2_LENS_ABI'],
  ['ToshLaunchpadHook', 'V2_HOOK_ABI'],
  ['ToshFactory', 'V2_FACTORY_ABI'],
  ['ToshToken', 'V2_TOKEN_ABI'],
]

let body =
  '// GENERATED by scripts/genV2Abis.mjs from the Foundry build. Do not edit.\n\n'
for (const [name, exportName] of CONTRACTS) {
  const json = JSON.parse(readFileSync(resolve(out, `${name}.sol/${name}.json`), 'utf8'))
  body += `export const ${exportName} = ${JSON.stringify(json.abi, null, 2)} as const\n\n`
}

if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8')
  if (current !== body) {
    console.error('src/lib/v2/abis.ts is stale: run `node scripts/genV2Abis.mjs`')
    process.exit(1)
  }
  console.log('v2 ABIs match the build')
} else {
  writeFileSync(target, body)
  console.log(`wrote ${target}`)
}
